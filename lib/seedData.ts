// Helper to determine cleaner category group from raw code/description
function resolveGroup(code: string, desc: string): string {
  const c = code.toUpperCase().trim();
  const d = desc.toUpperCase().trim();
  if (c.includes('MAT.PRI') || d.includes('BARRA CHATA') || d.includes('CANTONEIRA') || d.includes('CHAPA') || d.includes('EIXO') || d.includes('TUBO') || d.includes('VIGA')) {
    return 'MATÉRIA PRIMA';
  }
  if (c.includes('MOTOR') || d.includes('MOTOR ') || d.includes('RED IBR') || d.includes('REDUTOR') || d.includes('BRAÇO DE TORQUE')) {
    return 'MOTORES & REDUTORES';
  }
  if (c.includes('NEYLON') || d.includes('POLIACETAL') || d.includes('POLIPROPILENO')) {
    return 'POLÍMEROS & NEYLON';
  }
  if (c.includes('PNEUM') || d.includes('CONEXÃO') || d.includes('COTOVELO') || d.includes('SILENCIADOR') || d.includes('TAMPÃO') || d.includes('UNIÃO')) {
    return 'PNEUMÁTICA';
  }
  if (d.includes('PARAFUSO') || d.includes('PORCA') || d.includes('ARRUELA')) {
    return 'FIXADORES & PARAFUSOS';
  }
  if (d.includes('ROLAMENTO') || d.includes('MANCAL') || d.includes('GUIA LINEAR') || d.includes('BLOCO')) {
    return 'ROLAMENTOS & GUIAS';
  }
  if (d.includes('CORRENTE') || d.includes('EMENDA') || d.includes('ENGRENAGEM') || d.includes('REDUÇÃO ASA')) {
    return 'TRANSMISSÃO & ENGRENAGENS';
  }
  return 'INSUMOS GERAIS';
}

export function generateSeedCatalog(): CatalogItem[] {
  return RAW_ITEMS_DATA.map((item, index) => {
    const rawCode = item[0];
    const desc = item[1];
    const unit = item[2];
    const weight = item[3];
    const group = resolveGroup(rawCode, desc);
    const id = `item-${index + 1}`;
    const code = `${rawCode.replace('.', '')}-${String(index + 1).padStart(4, '0')}`;

    return {
      id,
      code,
      description: desc,
      group,
      unit,
      cost: 0,
      weightBar: weight || 0,
      notes: weight > 0 ? `Peso ref. barra/unidade: ${weight} kg` : '',
      createdAt: new Date().toISOString(),
    };
  });
}

